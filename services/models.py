"""
Общие Pydantic-модели данных, используемые всеми сервисами.

Вынесены из парсеров, чтобы бот мог десериализовать JSON из API
без импорта тяжёлых модулей парсинга (httpx, docx, etc).
"""

from datetime import date

from pydantic import BaseModel


class Lesson(BaseModel):
    """Модель данных одного учебного занятия в расписании."""

    # Порядковый индекс слота пары в сетке времени (0-5)
    period: int
    # Строковый временной диапазон пары (например, '09:00 - 10:30')
    time_str: str
    # Наименование учебной дисциплины
    subject: str
    # Тип занятия (лекция, практика, лабораторная)
    lesson_type: str
    # ФИО преподавателя
    teacher: str
    # Флаг дистанционного формата проведения
    is_remote: bool
    # Номер или название учебной аудитории
    room: str
    # Физический адрес учебного корпуса
    address: str
    # Номер подгруппы (0 - вся группа, 1 или 2 - подгруппа)
    subgroup: int = 0
    # Признак потоковой лекции для нескольких групп
    is_stream: bool = False
    # Ссылка на подключение к видеоконференции (Zoom, Teams, etc)
    remote_link: str | None = None
    # Пароль/код доступа к дистанционной конференции
    remote_passcode: str | None = None
    # Идентификатор конференции
    remote_meeting_id: str | None = None

    @property
    def number(self) -> int:
        """
        Преобразует нулевой индекс периода в академический номер пары.

        Используется в шаблонах сообщений Telegram для привычной нумерации 1..6
        вместо внутреннего программного смещения 0..5.

        Возвращает целочисленный номер пары (от 1 до 6).
        """
        return self.period + 1


# Кабинет аттестации ещё не назначен в сетке — корпус тоже неизвестен
EXAM_ROOM_TBD = "Кабинет уточняется"


class ExamItem(BaseModel):
    """Модель контрольного мероприятия, зачета или экзаменационной сессии."""

    # Наименование дисциплины аттестации
    subject: str
    # Нормализованный тип мероприятия (Экзамен, Зачет, Консультация)
    exam_type: str
    # ФИО принимающего преподавателя
    teacher: str
    # Аудитория проведения
    room: str
    # Адрес корпуса; пустой, если кабинет ещё не назначен (EXAM_ROOM_TBD)
    address: str
    # Список учебных недель проведения мероприятия
    weeks: list[int]
    # Подгруппа (0 - вся группа)
    subgroup: int = 0
    # Текстовый формат проведения ('Очно' / 'Дистанционно')
    format_str: str = "Очно"
    # Дата аттестации, если она уже поставлена в сетку; None — известна только неделя
    exam_date: date | None = None
    # Академический номер пары (1..7) в день аттестации; None — слот не назначен
    pair_number: int | None = None
    # Звонки пары ('13:45–15:10'); None — слот не назначен
    time_str: str | None = None
    # Неделя ещё не опубликована на сайте КТМУ — данные из черновика и могут измениться
    is_preliminary: bool = False
