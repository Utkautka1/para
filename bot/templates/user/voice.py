"""
Шаблоны сообщений для расшифровки голосовых и видеосообщений в Telegram.

Формирует аккуратные HTML-сообщения со статусом распознавания,
экранированием имени автора и цитатой расшифрованного текста,
а также сообщениями об ошибках и пустых аудиозаписях.
"""

import html


def format_transcription_status() -> str:
    """
    Возвращает текст временного статуса начала распознавания аудиосообщения.

    Отображается в первичном ответе бота до завершения работы модели faster-whisper.
    Информирует пользователя об активном процессе транскрибации.

    Возвращает строку с HTML-курсивом.
    """

    return "🎙 <i>Расшифровываю аудиосообщение...</i>"


def format_duration_str(duration_seconds: int) -> str:
    """
    Форматирует хронометраж аудиосообщения в формат (минуты:секунды).

    Возвращает пустую строку, если длительность не определена или <= 0.
    Защищает от некорректных отрицательных значений тайминга.

    Возвращает строку вида ' (1:05)' или пустую строку.
    """

    if duration_seconds <= 0:
        return ""

    mins = duration_seconds // 60
    secs = duration_seconds % 60

    return f" ({mins}:{secs:02d})"


def format_transcription_result(
    sender_name: str,
    duration_sec: int,
    transcription_text: str
) -> str:
    """
    Формирует красивое итоговое сообщение с расшифрованным текстом речи.

    Экранирует имя отправителя и текст для предотвращения инъекций Telegram HTML.
    Выделяет автора жирным шрифтом и заключает текст в кавычки.

    Возвращает валидный HTML-текст результата распознавания.
    """

    safe_name = html.escape(sender_name)
    safe_text = html.escape(transcription_text.strip())
    dur_str = format_duration_str(duration_sec)

    return (
        f"🗣 <b>{safe_name}</b>{dur_str}:\n\n"
        f"«{safe_text}»"
    )


def format_transcription_empty(sender_name: str, duration_sec: int) -> str:
    """
    Формирует уведомление о неразборчивой или тихой аудиозаписи.

    Используется, когда whisper не нашел речевых сегментов в аудиодорожке.
    Предотвращает отправку пустых сообщений в чат.

    Возвращает HTML-текст уведомления с именем автора.
    """

    safe_name = html.escape(sender_name)
    dur_str = format_duration_str(duration_sec)

    return (
        f"🗣 <b>{safe_name}</b>{dur_str}:\n\n"
        f"<i>(В аудиозаписи не удалось разобрать речь)</i>"
    )


def format_transcription_error() -> str:
    """
    Возвращает сообщение о техническом сбое при обработке аудиофайла.

    Показывается при падении конвертера ffmpeg или нехватке видеопамяти.
    Обеспечивает понятную обратную связь пользователю без раскрытия стектрейса.

    Возвращает HTML-строку с предупреждением.
    """

    return "⚠️ <i>Не удалось расшифровать аудиосообщение. Попробуйте позже.</i>"


def format_too_long_error(max_seconds: int = 300) -> str:
    """
    Возвращает предупреждение о превышении допустимого хронометража аудио.

    Защищает серверный инференс GPU от перегрузки гигантскими аудиокнигами/лекциями.
    Информирует о максимально допустимой длительности в минутах.

    Возвращает HTML-текст предупреждения.
    """

    mins = max_seconds // 60

    return f"⚠️ <i>Аудиосообщение слишком длинное (максимум {mins} мин).</i>"


def format_too_big_error(max_mb: int = 20) -> str:
    """
    Возвращает предупреждение о превышении максимального размера файла.

    Служит защитой дискового пространства и канала от скачивания больших файлов.
    Ограничивает загрузку в пределах лимитов Telegram Bot API.

    Возвращает HTML-текст ошибки размера файла.
    """

    return f"⚠️ <i>Аудиофайл слишком большой (максимум {max_mb} МБ).</i>"


def format_rate_limit_error() -> str:
    """
    Возвращает сообщение о троттлинге параллельных запросов одного пользователя.

    Защищает от исчерпания очереди при спаме пачкой голосовых сообщений.
    Просит пользователя дождаться завершения текущей обработки.

    Возвращает HTML-строку с просьбой подождать.
    """

    return "⏳ <i>Подождите, ваше предыдущее аудиосообщение ещё обрабатывается.</i>"


def format_queue_status(queue_pos: int) -> str:
    """
    Возвращает текст статуса нахождения аудиосообщения в очереди на GPU.

    Показывает порядковый номер в очереди при высокой нагрузке на транскрибатор.
    Регулярно обновляется через edit_text в фоновом процессе.

    Возвращает HTML-строку с позицией в очереди.
    """

    return f"🎙 <i>В очереди на расшифровку (позиция: {queue_pos})...</i>"

